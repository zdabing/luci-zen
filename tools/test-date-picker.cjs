const fs=require('node:fs'),assert=require('node:assert/strict');
const source=fs.readFileSync('luci-app-zen-traffic/htdocs/luci-static/resources/view/zen-traffic/date-picker.js','utf8');
const picker=new Function('baseclass','trafficStyle',source)({extend:p=>p},{});
assert.equal(picker.parse('2026-02-29'),null);
assert.ok(picker.parse('2024-02-29'));
assert.equal(picker.parse('2026-04-31'),null);
assert.equal(picker.shift('2024-02-28',1),'2024-02-29');
assert.equal(picker.shift('2026-12-31',1),'2027-01-01');
assert.equal(picker.shift('2026-03-08',1),'2026-03-09','Calendar dates do not skip days at DST changes');
assert.equal(picker.shiftMonth('2024-01-31',1),'2024-02-29');
assert.equal(picker.shiftMonth('2026-03-31',-1),'2026-02-28');
assert.equal(picker.shiftMonth('2024-02-29',12),'2025-02-28');
const days=picker.monthDays('2026-10-21');
assert.equal(days.length,42);assert.equal(days[0],'2026-09-28');assert.equal(days.at(-1),'2026-11-08');
for(let i=1;i<days.length;i++)assert.equal(days[i],picker.shift(days[i-1],1));
assert.equal(picker.selectable('2026-10-22','','2026-10-21'),false,'Future router dates are disabled');
assert.equal(picker.selectable('2026-10-01','2026-10-02','2026-10-21'),false);
assert.equal(picker.selectable('2026-10-21','2026-10-02','2026-10-21'),true);
assert.equal(picker.selectable('2026-02-30'),false);
console.log('PASS: calendar boundaries, leap years, DST-safe navigation and date constraints');
