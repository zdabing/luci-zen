const fs=require('node:fs'),assert=require('node:assert/strict');
String.prototype.format=function(...values){return this.replace(/%[ds]/g,()=>String(values.shift()));};
const info=new Function('baseclass','_',fs.readFileSync('luci-theme-zen/htdocs/luci-static/resources/view/zen/zen-connection-info.js','utf8'))({extend:x=>x},x=>x);
const original=Date.now;Date.now=()=>100000;
const raw={conn:'wired',online:false,last:42};
assert.equal(info.merge(raw,null,100000),raw);
assert.equal(info.merge(raw,{kind:'wifi',connected_seconds:4},0),raw,'Stale telemetry cannot extend a connection indefinitely');
const wifi=info.merge(raw,{kind:'wifi',signal_dbm:-58,connected_seconds:12000,upload_mbps:433.3,download_mbps:866.7,band:'5GHz'},98000);
assert.equal(wifi.connected_seconds,12002);assert.equal(wifi.online,true);
assert.match(info.connection(wifi),/-58 dBm/);assert.equal(info.duration(wifi.connected_seconds),'3h 20m');
assert.match(info.linkRate(wifi),/433.3 Mbps.*866.7 Mbps/);
assert.equal(info.duration(null),null);assert.equal(info.duration(-1),null);
assert.doesNotMatch(info.status({...raw,online:true}),/Connected/,'Wired presence does not invent an association time');
assert.match(info.status(raw),/^Last active /);
const wired=info.merge(raw,{kind:'wired',port:'lan1',port_speed_mbps:2500},100000);
assert.match(info.connection(wired),/lan1.*2.5 Gbps/);
assert.equal(info.linkRate({...wired,port_speed_mbps:-1}),null);
Date.now=original;
console.log('PASS: fresh connection metadata, exact Wi-Fi duration, port-rate labels, offline activity and missing/stale fields');
